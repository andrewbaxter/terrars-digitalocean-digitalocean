pub struct BuildDataVolumeSnapshot {
    pub tf_id: std::string::String,
}

impl BuildDataVolumeSnapshot {
    pub fn build(self, stack: &mut terrars::Stack) -> DataVolumeSnapshot {
        let out = DataVolumeSnapshot(std::rc::Rc::new(DataVolumeSnapshot_ {
            shared: stack.shared.clone(),
            tf_id: self.tf_id,
            data: std::cell::RefCell::new(DataVolumeSnapshotData_ {
                depends_on: core::default::Default::default(),
                provider: std::option::Option::None,
                lifecycle: core::default::Default::default(),
                for_each: std::option::Option::None,
                id: core::default::Default::default(),
                most_recent: core::default::Default::default(),
                name: core::default::Default::default(),
                name_regex: core::default::Default::default(),
                region: core::default::Default::default(),
            }),
        }));
        stack.add_datasource(out.0.clone());
        out
    }
}

