pub struct BuildUptimeCheck {
    pub tf_id: std::string::String,
    #[doc = "A human-friendly display name for the check."]
    pub name: terrars::PrimField<std::string::String>,
    #[doc = "The endpoint to perform healthchecks on."]
    pub target: terrars::PrimField<std::string::String>,
}

impl BuildUptimeCheck {
    pub fn build(self, stack: &mut terrars::Stack) -> UptimeCheck {
        let out = UptimeCheck(std::rc::Rc::new(UptimeCheck_ {
            shared: stack.shared.clone(),
            tf_id: self.tf_id,
            data: std::cell::RefCell::new(UptimeCheckData_ {
                depends_on: core::default::Default::default(),
                provider: std::option::Option::None,
                lifecycle: core::default::Default::default(),
                for_each: std::option::Option::None,
                provisioner: core::default::Default::default(),
                enabled: core::default::Default::default(),
                name: self.name,
                regions: core::default::Default::default(),
                target: self.target,
                type_: core::default::Default::default(),
            }),
        }));
        stack.add_resource(out.0.clone());
        out
    }
}

