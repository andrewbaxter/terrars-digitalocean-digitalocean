pub struct BuildVolume {
    pub tf_id: std::string::String,
    #[doc = ""]
    pub name: terrars::PrimField<std::string::String>,
    #[doc = ""]
    pub region: terrars::PrimField<std::string::String>,
    #[doc = ""]
    pub size: terrars::PrimField<f64>,
}

impl BuildVolume {
    pub fn build(self, stack: &mut terrars::Stack) -> Volume {
        let out = Volume(std::rc::Rc::new(Volume_ {
            shared: stack.shared.clone(),
            tf_id: self.tf_id,
            data: std::cell::RefCell::new(VolumeData_ {
                depends_on: core::default::Default::default(),
                provider: std::option::Option::None,
                lifecycle: core::default::Default::default(),
                for_each: std::option::Option::None,
                provisioner: core::default::Default::default(),
                description: core::default::Default::default(),
                filesystem_type: core::default::Default::default(),
                id: core::default::Default::default(),
                initial_filesystem_label: core::default::Default::default(),
                initial_filesystem_type: core::default::Default::default(),
                name: self.name,
                region: self.region,
                size: self.size,
                snapshot_id: core::default::Default::default(),
                tags: core::default::Default::default(),
            }),
        }));
        stack.add_resource(out.0.clone());
        out
    }
}

