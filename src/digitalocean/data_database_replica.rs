impl BuildDataDatabaseReplica {
    pub fn build(self, stack: &mut terrars::Stack) -> DataDatabaseReplica {
        let out = DataDatabaseReplica(std::rc::Rc::new(DataDatabaseReplica_ {
            shared: stack.shared.clone(),
            tf_id: self.tf_id,
            data: std::cell::RefCell::new(DataDatabaseReplicaData_ {
                depends_on: core::default::Default::default(),
                provider: std::option::Option::None,
                lifecycle: core::default::Default::default(),
                for_each: std::option::Option::None,
                cluster_id: self.cluster_id,
                id: core::default::Default::default(),
                name: self.name,
                tags: core::default::Default::default(),
            }),
        }));
        stack.add_datasource(out.0.clone());
        out
    }
}

