pub struct BuildDataReservedIp {
    pub tf_id: std::string::String,
    #[doc = "reserved ip address"]
    pub ip_address: terrars::PrimField<std::string::String>,
}

impl BuildDataReservedIp {
    pub fn build(self, stack: &mut terrars::Stack) -> DataReservedIp {
        let out = DataReservedIp(std::rc::Rc::new(DataReservedIp_ {
            shared: stack.shared.clone(),
            tf_id: self.tf_id,
            data: std::cell::RefCell::new(DataReservedIpData {
                depends_on: core::default::Default::default(),
                provider: std::option::Option::None,
                lifecycle: core::default::Default::default(),
                for_each: std::option::Option::None,
                id: core::default::Default::default(),
                ip_address: self.ip_address,
            }),
        }));
        stack.add_datasource(out.0.clone());
        out
    }
}

